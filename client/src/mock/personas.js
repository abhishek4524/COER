export const generate50Personas = () => {
  const list = [...personasData];
  for (let i = 13; i <= 50; i++) {
    const basePersona = personasData[(i - 1) % personasData.length];
    const name = names[(i - 13) % names.length] + ' ' + String.fromCharCode(65 + (i % 26)) + '.';
    const missedCTA = i <= 38;
    list.push({
      id: `p${i}`,
      name: name,
      age: 18 + (i * 3) % 55,
      role: i % 3 === 0 ? 'Mobile User' : i % 2 === 0 ? 'Desktop Browser' : 'Tablet Skimmer',
      tag: missedCTA ? 'Friction User' : 'Converted User',
      quote: missedCTA ? 'Could not locate the action button.' : 'Smooth checkout experience!',
      avatar: basePersona.avatar,
      altAvatar: basePersona.altAvatar,
      device: i % 2 === 0 ? 'Mobile Safari' : 'Chrome Desktop',
      patience: 20 + (i * 7) % 70,
      techSavvy: 30 + (i * 5) % 65,
      visionScore: 50 + (i * 3) % 45,
      frictionPoint: missedCTA ? 'Missed secondary CTA link' : 'None',
      missedCTA: missedCTA,
      status: missedCTA ? 'confused' : 'converted',
      color: missedCTA ? '#F08A7E' : '#8FB8A8',
    });
  }
  return list;
};

export const all50Personas = generate50Personas();

